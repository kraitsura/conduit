// TestCommitLogParsing tests parsing of git log output format.
func TestCommitLogParsing(t *testing.T) {
	// Format: hash|author|email|timestamp|message
	tests := []struct {
		name        string
		line        string
		wantHash    string
		wantAuthor  string
		wantEmail   string
		wantMessage string
		wantValid   bool
	}{
		{
			name:        "standard commit line",
			line:        "abc123def456|John Doe|john@example.com|1704067200|feat: add feature",
			wantHash:    "abc123def456",
			wantAuthor:  "John Doe",
			wantEmail:   "john@example.com",
			wantMessage: "feat: add feature",
			wantValid:   true,
		},
		{
			name:        "message with pipe character",
			line:        "abc123|Jane|jane@test.com|1704067200|fix: handle | in strings",
			wantHash:    "abc123",
			wantAuthor:  "Jane",
			wantEmail:   "jane@test.com",
			wantMessage: "fix: handle | in strings",
			wantValid:   true,
		},
		{
			name:        "empty message",
			line:        "abc123|Author|email@test.com|1704067200|",
			wantHash:    "abc123",
			wantAuthor:  "Author",
			wantEmail:   "email@test.com",
			wantMessage: "",
			wantValid:   true,
		},
		{
			name:      "too few parts",
			line:      "abc123|Author|email@test.com",
			wantValid: false,
		},
		{
			name:      "empty line",
			line:      "",
			wantValid: false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			// Simulate the parsing logic from GetRecentCommits
			if tt.line == "" {
				if tt.wantValid {
					t.Error("empty line should not be valid")
				}
				return
			}

			parts := splitN(tt.line, "|", 5)
			valid := len(parts) >= 5

			if valid != tt.wantValid {
				t.Errorf("parsing validity: got %v, want %v", valid, tt.wantValid)
				return
			}

			if !tt.wantValid {
				return
			}

			if parts[0] != tt.wantHash {
				t.Errorf("hash: got %q, want %q", parts[0], tt.wantHash)
			}
			if parts[1] != tt.wantAuthor {
				t.Errorf("author: got %q, want %q", parts[1], tt.wantAuthor)
			}
			if parts[2] != tt.wantEmail {
				t.Errorf("email: got %q, want %q", parts[2], tt.wantEmail)
			}
			if parts[4] != tt.wantMessage {
				t.Errorf("message: got %q, want %q", parts[4], tt.wantMessage)
			}
		})
	}
}

// splitN is a test helper that mimics strings.SplitN behavior
func splitN(s, sep string, n int) []string {
	if n == 0 {
		return nil
	}
	if n < 0 {
		n = len(s) + 1
	}

	result := make([]string, 0, n)
	for i := 0; i < n-1; i++ {
		idx := -1
		for j := 0; j < len(s); j++ {
			if j+len(sep) <= len(s) && s[j:j+len(sep)] == sep {
				idx = j
				break
			}
		}
		if idx < 0 {
			break
		}
		result = append(result, s[:idx])
		s = s[idx+len(sep):]
	}
	result = append(result, s)
	return result
}

