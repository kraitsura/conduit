// TestIsAICommit verifies AI commit detection across various author/email/message patterns.
// This is a critical function that determines how commits are categorized.
func TestIsAICommit(t *testing.T) {
	tests := []struct {
		name    string
		author  string
		email   string
		message string
		want    bool
	}{
		// Claude patterns
		{
			name:    "claude in author name",
			author:  "Claude",
			email:   "user@example.com",
			message: "fix: resolve bug",
			want:    true,
		},
		{
			name:    "claude lowercase in author",
			author:  "claude assistant",
			email:   "user@example.com",
			message: "refactor code",
			want:    true,
		},
		{
			name:    "claude in message co-author",
			author:  "John Doe",
			email:   "john@example.com",
			message: "fix: bug fix\n\nCo-Authored-By: Claude <noreply@anthropic.com>",
			want:    true,
		},

		// Cursor patterns
		{
			name:    "cursor in author",
			author:  "Cursor",
			email:   "user@example.com",
			message: "add feature",
			want:    true,
		},
		{
			name:    "cursor lowercase",
			author:  "cursor-ai",
			email:   "user@example.com",
			message: "implement feature",
			want:    true,
		},

		// Copilot patterns
		{
			name:    "copilot in author",
			author:  "GitHub Copilot",
			email:   "copilot@github.com",
			message: "generated code",
			want:    true,
		},
		{
			name:    "copilot in message",
			author:  "Developer",
			email:   "dev@company.com",
			message: "feat: add function (via copilot)",
			want:    true,
		},

		// Aider patterns
		{
			name:    "aider in author",
			author:  "aider",
			email:   "aider@local",
			message: "refactor",
			want:    true,
		},
		{
			name:    "aider in message",
			author:  "John",
			email:   "john@example.com",
			message: "feat: implemented with aider",
			want:    true,
		},

		// Generic AI patterns
		{
			name:    "ai word boundary in author",
			author:  "AI Assistant",
			email:   "user@example.com",
			message: "fix bug",
			want:    true,
		},
		{
			name:    "ai word boundary in message",
			author:  "Developer",
			email:   "dev@example.com",
			message: "feat: generated by AI",
			want:    true,
		},
		{
			name:    "assistant in author",
			author:  "Code Assistant",
			email:   "user@example.com",
			message: "update code",
			want:    true,
		},

		// Automated patterns
		{
			name:    "automated in author",
			author:  "Automated Build",
			email:   "build@ci.com",
			message: "bump version",
			want:    true,
		},
		{
			name:    "automated in message",
			author:  "CI Bot",
			email:   "ci@example.com",
			message: "automated: update dependencies",
			want:    true,
		},

		// Bot email patterns
		{
			name:    "bot@ in email",
			author:  "Release Bot",
			email:   "bot@company.com",
			message: "release v1.0.0",
			want:    true,
		},

		// Noreply patterns
		{
			name:    "noreply@ in email",
			author:  "GitHub Actions",
			email:   "noreply@github.com",
			message: "update workflow",
			want:    true,
		},

		// Human commits (should NOT be detected as AI)
		{
			name:    "regular human commit",
			author:  "John Doe",
			email:   "john@example.com",
			message: "feat: add new feature",
			want:    false,
		},
		{
			name:    "human commit with fix prefix",
			author:  "Jane Smith",
			email:   "jane@company.org",
			message: "fix: resolve memory leak",
			want:    false,
		},
		{
			name:    "human commit mentioning tools",
			author:  "Developer",
			email:   "dev@example.com",
			message: "docs: update README",
			want:    false,
		},
		{
			name:    "email containing ai but not word boundary",
			author:  "Kai",
			email:   "kai@domain.com",
			message: "fix: typo",
			want:    false,
		},
		{
			name:    "email with domain containing ai",
			author:  "User",
			email:   "user@aicompany.com",
			message: "update",
			want:    false,
		},
		{
			name:    "name containing ai substring",
			author:  "Kaito",
			email:   "kaito@example.com",
			message: "refactor module",
			want:    false,
		},

		// Edge cases
		{
			name:    "empty fields",
			author:  "",
			email:   "",
			message: "",
			want:    false,
		},
		{
			name:    "mixed case Claude",
			author:  "CLAUDE",
			email:   "user@example.com",
			message: "fix",
			want:    true,
		},
		{
			name:    "claude in email domain",
			author:  "User",
			email:   "user@claude.ai",
			message: "update",
			want:    true,
		},
		{
			name:    "generated with Claude Code marker",
			author:  "Developer",
			email:   "dev@company.com",
			message: "feat: add auth\n\n🤖 Generated with Claude Code",
			want:    true,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := isAICommit(tt.author, tt.email, tt.message)
			if got != tt.want {
				t.Errorf("isAICommit(%q, %q, %q) = %v, want %v",
					tt.author, tt.email, tt.message, got, tt.want)
			}
		})
	}
}

// TestAIPatternsComprehensive ensures all defined patterns work correctly.
func TestAIPatternsComprehensive(t *testing.T) {
	// Verify the aiPatterns slice has the expected patterns
	expectedPatternCount := 9
	if len(aiPatterns) != expectedPatternCount {
		t.Errorf("expected %d AI patterns, got %d", expectedPatternCount, len(aiPatterns))
	}

	// Test each pattern matches its target string
	patternTests := []struct {
		pattern string
		input   string
		matches bool
	}{
		{"claude", "Claude Code", true},
		{"cursor", "Cursor IDE", true},
		{"copilot", "GitHub Copilot", true},
		{"aider", "aider tool", true},
		{`\bai\b`, "AI generated", true},
		{`\bai\b`, "aicompany", false}, // Should not match
		{"assistant", "AI Assistant", true},
		{"automated", "automated commit", true},
		{"bot@", "bot@github.com", true},
		{"noreply@", "noreply@example.com", true},
	}

	for _, tt := range patternTests {
		found := false
		for _, re := range aiPatterns {
			if re.MatchString(tt.input) {
				found = true
				break
			}
		}
		if found != tt.matches {
			t.Errorf("pattern %q against %q: got match=%v, want %v",
				tt.pattern, tt.input, found, tt.matches)
		}
	}
}

